def test_apply_after_destroy_rebuilds_the_same_catalog(org, run_entrust):
    """Destroy purges what it deleted from the recycle bin and a rebuild is a clean first apply again —
    except the AttributeDefinition, which never reaches the bin and keeps its DeveloperName: the rebuilt
    one comes back suffixed and the engine accepts it (the 7 Oct landmine, back with this catalog)."""
    run_entrust("apply")
    code, out = run_entrust("destroy", "--yes")
    assert code == 0, out
    assert total(out, "Purged") == OWNED
    assert not org.bin["Product2"] and not org.bin["RateCard"] and not org.bin["UsageResource"]
    assert org.bin["AttributeDefinition"]
    code, out = run_entrust("apply")
    assert code == 0, out
    assert total(out, "Created") == OWNED and total(out, "Warnings") == 0
    rebuilt = org.one("AttributeDefinition", Code="ATTR-DOC-CHECK-FEATURE")
