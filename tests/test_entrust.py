def test_nothing_a_quote_can_show_names_an_m3ter_identifier():
    """Decided 7 Oct 2026: no m3ter accounting-product or meter code anywhere a quote template can read.
    Product and resource names, codes and descriptions are the commercial names."""
    meters = ("document_report", "facial_similarity", "known_faces", "proof_of_address", "repeat_attempts",
              "applicant_fraud", "autofill_count", "CPQ_ID", "_count")
    for path in ENTRUST_CONFIG.glob("*.json"):
        for block in load(path)["objects"]:
            for record in block["records"]:
                for field, value in record.items():
                    if field.startswith("@") or not isinstance(value, str) or value.startswith("@ref:"):
                        continue
                    assert not any(m.lower() in value.lower() for m in meters), f"{path.name}: {field} = {value!r}"


def test_the_rate_card_entries_are_keyed_by_resource():
    """With one product, (RateCardId, ProductId) names six entries per card; the key must include the
    resource or `check` reports records with the same match key. Both cards carry one entry per resource."""
    for name in ("09b-list-rate-card.json", "09c-commit-rate-card.json"):
        entries = block_of(load(ENTRUST_CONFIG / name), "RateCardEntry")
        assert entries["match_fields"] == ["RateCardId", "ProductId", "UsageResourceId"]
        assert len({r["UsageResourceId"] for r in entries["records"]}) == RESOURCES == len(entries["records"])


def test_the_commit_card_entries_carry_tiers_not_rates():
    data = load(ENTRUST_CONFIG / "09c-commit-rate-card.json")
    assert block_of(data, "RateCard")["records"][0]["Type"] == "Tier"
    assert all("Rate" not in r for r in block_of(data, "RateCardEntry")["records"])
    tiers = block_of(data, "RateAdjustmentByTier")
    assert tiers["match_fields"] == ["RateCardEntryId", "LowerBound"]
    assert len(tiers["records"]) == RESOURCES * TIERS
    by_entry: dict[str, list[dict]] = {}
    for t in tiers["records"]:
        by_entry.setdefault(t["RateCardEntryId"], []).append(t)
    for bands in by_entry.values():
        bands.sort(key=lambda t: t["LowerBound"])
        assert [(t["LowerBound"], t.get("UpperBound")) for t in bands] == [(0, 10000), (10000, 25000), (25000, None)]
        assert {t["AdjustmentType"] for t in bands} == {"Override"}


def test_one_command_builds_the_catalog_from_the_pre_seed(org, run_entrust):
    counts_before = {name: org.count(name) for name in org.rows}
    code, out = run_entrust("apply")
    assert code == 0, out
    assert total(out, "Created") == OWNED
    assert total(out, "Updated") == 0
    assert total(out, "Linked") == LINKED
    assert total(out, "Found (org-owned)") == ANCHORS
    assert total(out, "Activated") == ACTIVATED
    assert total(out, "Errors") == 0
    assert total(out, "Warnings") == 0
    assert sorted(org.refreshes) == sorted(TABLES)
    assert len(org.writes()) == OWNED + LINKED + ACTIVATED + RESENT

    # the unit-of-measure pair: class activated, default unit filled in by the forward reference
    cls = org.one("UnitOfMeasureClass", Code="UOM-CLASS-VERIFICATION-USAGE")
    check = org.one("UnitOfMeasure", UnitCode="VERIFICATION-CHECK")
    assert cls["Status"] == "Active" and cls["DefaultUnitOfMeasureId"] == check["Id"]
    assert check["UnitOfMeasureClassId"] == cls["Id"] and check["Type"] == "Custom"
    assert org.count("UnitOfMeasureClass") == 3          # Token, Currency, Verification
    # the attribute: a required, non-price-impacting selector on the classification the product is based on
    attr = org.one("AttributeDefinition", Code="ATTR-DOC-CHECK-FEATURE")
    assert attr["DeveloperName"] == "Document_Check_Feature_Type" and attr["DataType"] == "Picklist"
    values = [r for r in org.rows["AttributePicklistValue"].values() if r["PicklistId"] == attr["PicklistId"]]
    assert sorted((v["Sequence"], v["Code"], v["IsDefault"]) for v in values) == [
        (1, "FLASH", True), (2, "BOOST", False), (3, "SHERLOCK", False)]
    pca = org.one("ProductClassificationAttr", AttributeDefinitionId=attr["Id"])
    assert pca["IsRequired"] is True and pca["IsPriceImpacting"] is False
    # ONE product: an Anchor in USD, configured during sale, based on the classification, 0.00 USD monthly
    products = [r for r in org.rows["Product2"].values() if str(r.get("ProductCode", "")).startswith("VC-")]
    assert len(products) == 1
    product = products[0]
    assert product["ProductCode"] == PRODUCT_CODE and product["Name"] == "Document Check"
    assert product["UsageModelType"] == "Anchor" and product["CurrencyIsoCode"] == "USD"
    assert product["ConfigureDuringSale"] == "Allowed"
    assert product["BasedOnId"] == org.one("ProductClassification", Code="PC-DOC-CHECK")["Id"]
    monthly = org.one("ProductSellingModel", SellingModelType="TermDefined", PricingTermUnit="Months")["Id"]
    assert org.count("ProductSellingModelOption", Product2Id=product["Id"]) == 1
    entries = [r for r in org.rows["PricebookEntry"].values() if r["Product2Id"] == product["Id"]]
    assert [(e["CurrencyIsoCode"], e["UnitPrice"], e["ProductSellingModelId"]) for e in entries] == [
        ("USD", 0.0, monthly)]
    # SIX usage resources, feature x region, all defined by and linked to the one product
    resources = [r for r in org.rows["UsageResource"].values() if str(r.get("Code", "")).startswith("RES-DOC-CHECK-")]
    assert len(resources) == RESOURCES
    assert {r["DefaultUnitOfMeasureId"] for r in resources} == {check["Id"]}
    assert {r["UsageDefinitionProductId"] for r in resources} == {product["Id"]}
    assert {r["Status"] for r in resources} == {"Active"}
    assert {r["Name"] for r in resources} == {f"Document Check - {f} - {g}"
                                              for f in ("Flash", "Boost", "Sherlock") for g in ("USA", "ANY")}
    links = [r for r in org.rows["ProductUsageResource"].values() if r["ProductId"] == product["Id"]]
    assert len(links) == RESOURCES and {r["Status"] for r in links} == {"Active"}
    assert {r["EffectiveStartDate"] for r in links} == {EFFECTIVE}
    assert {r["UsageResourceId"] for r in links} == {r["Id"] for r in resources}
    # each link carries a 0-quantity Grant and a policy row; the product has one Self binding policy
    link_ids = {r["Id"] for r in links}
    grants = [r for r in org.rows["ProductUsageGrant"].values() if r["ProductUsageResourceId"] in link_ids]
    assert len(grants) == RESOURCES
    assert {(g["Type"], g["Quantity"], g["ValidityPeriodUnit"], g["Status"]) for g in grants} == {
        ("Grant", 0.0, "None", "Active")}
    overage = org.one("UsageOveragePolicy", Name="DC Usage Overage Policy")
    frequency = org.one("RatingFrequencyPolicy", Name="DC Monthly Rating Frequency")
    assert overage["OverageChargeable"] == "Yes" and frequency["RatingPeriod"] == "Monthly"
    policies = list(org.rows["ProductUsageResourcePolicy"].values())
    assert len(policies) == RESOURCES
    assert {(p["UsageOveragePolicyId"], p["RatingFrequencyPolicyId"]) for p in policies} == {
        (overage["Id"], frequency["Id"])}
    assert org.one("UsagePrdGrantBindingPolicy", Product2Id=product["Id"])["GrantBindingType"] == "Self"
    # TWO rate cards on the standard price book, one Negotiable Term Monthly USD entry per resource each
    usd = org.one("UnitOfMeasure", UnitCode="USD")["Id"]
    for name, kind in ((LIST_CARD, "Base"), (COMMIT_CARD, "Tier")):
        card = org.one("RateCard", Name=name)
        assert card["Type"] == kind and card["EffectiveFrom"] == EFFECTIVE
        assert org.count("PriceBookRateCard", RateCardId=card["Id"]) == 1
        rces = [r for r in org.rows["RateCardEntry"].values() if r["RateCardId"] == card["Id"]]
        assert len(rces) == RESOURCES
        assert {r["ProductId"] for r in rces} == {product["Id"]}
        assert {r["UsageResourceId"] for r in rces} == {r["Id"] for r in resources}
        assert {r["ProductSellingModelId"] for r in rces} == {monthly}
        assert {r["RateNegotiation"] for r in rces} == {"Negotiable"}
        assert {r["Status"] for r in rces} == {"Active"}
        assert {r["RateUnitOfMeasureId"] for r in rces} == {usd}
    # the List card carries the rates; the Commit card carries none and three tiers per entry instead
    list_card = org.one("RateCard", Name=LIST_CARD)["Id"]
    rate_of = {org.rows["UsageResource"][r["UsageResourceId"]]["Code"]: r["Rate"]
               for r in org.rows["RateCardEntry"].values() if r["RateCardId"] == list_card}
    assert rate_of["RES-DOC-CHECK-BOOST-USA"] == 5.75 and rate_of["RES-DOC-CHECK-SHERLOCK-ANY"] == 6.75
    commit_card = org.one("RateCard", Name=COMMIT_CARD)["Id"]
    commit = {r["Id"]: org.rows["UsageResource"][r["UsageResourceId"]]["Code"]
              for r in org.rows["RateCardEntry"].values() if r["RateCardId"] == commit_card}
    assert all(org.rows["RateCardEntry"][i].get("Rate") is None for i in commit)
    tiers = [t for t in org.rows["RateAdjustmentByTier"].values() if t["RateCardEntryId"] in commit]
    assert len(tiers) == RESOURCES * TIERS
    assert {t["RateCardEntryStatus"] for t in tiers} == {"Active"}       # the mirror column follows the entry
    boost_usa = sorted((t["LowerBound"], t.get("UpperBound"), t["AdjustmentValue"]) for t in tiers
                       if commit[t["RateCardEntryId"]] == "RES-DOC-CHECK-BOOST-USA")
    assert boost_usa == [(0.0, 10000.0, 0.65), (10000.0, 25000.0, 0.5), (25000.0, None, 0.4)]
    # no attribute-based adjustment, no commitment
    for name in ("RateAdjustmentByAttribute", "AttributeBasedAdjRule", "UsageCommitmentPolicy"):
        assert org.count(name) == counts_before[name], name


def test_tiers_go_in_before_the_entry_is_activated(org, run_entrust):
    """The org refuses a tier on an Active entry (and the simulated org with it): every
    RateAdjustmentByTier must be created before any Commit entry is activated."""
    run_entrust("apply")
    writes = org.writes()
    last_tier = max(i for i, c in enumerate(writes) if c[0] == "create" and c[1] == "RateAdjustmentByTier")
    commit_card = org.one("RateCard", Name=COMMIT_CARD)["Id"]
    commit_ids = {r["Id"] for r in org.rows["RateCardEntry"].values() if r["RateCardId"] == commit_card}
    first_activation = min(i for i, c in enumerate(writes)
                           if c[0] == "update" and c[1] == "RateCardEntry" and c[2] in commit_ids)
    assert last_tier < first_activation


def test_a_tier_on_an_active_entry_is_refused_by_the_org(org):
    """The rule the engine's ordering protects against, stated on the simulated org itself."""
    from rc_config.client import OrgError
    product = org.insert("Product2", ProductCode="X", Name="X", UsageModelType="Anchor")
    resource = org.insert("UsageResource", Code="RES-X", Name="X", Status="Active", UsageDefinitionProductId=product)
    card = org.insert("RateCard", Name="X Tier", Type="Tier")
    entry = org.create("RateCardEntry", {"RateCardId": card, "ProductId": product, "UsageResourceId": resource})
    org.create("RateAdjustmentByTier", {"RateCardEntryId": entry, "LowerBound": 0, "UpperBound": 100,
                                        "AdjustmentType": "Override", "AdjustmentValue": 1.0})
    org.update("RateCardEntry", entry, {"Status": "Active"})
    with pytest.raises(OrgError, match="related rate card entry is active"):
        org.create("RateAdjustmentByTier", {"RateCardEntryId": entry, "LowerBound": 100,
                                            "AdjustmentType": "Override", "AdjustmentValue": 0.5})
    base = org.insert("RateCard", Name="X Base", Type="Base")
    base_entry = org.create("RateCardEntry", {"RateCardId": base, "ProductId": product, "UsageResourceId": resource,
                                              "Rate": 2.0})
    with pytest.raises(OrgError, match="Tier rate card"):
        org.create("RateAdjustmentByTier", {"RateCardEntryId": base_entry, "LowerBound": 0,
                                            "AdjustmentType": "Override", "AdjustmentValue": 1.0})


def test_check_refuses_tier_bands_that_do_not_chain(run, tmp_path):
    """Bands must chain (the upper of one is the lower of the next) and the last must be open; a Tier
    entry with no tiers prices nothing — all caught offline, before anything is sent."""
    target = copy_config(tmp_path)
    path = target / "09c-commit-rate-card.json"
    data = load(path)
    tiers = block_of(data, "RateAdjustmentByTier")["records"]
    boost = [t for t in tiers if t["RateCardEntryId"] == "@ref:RCE_Commit_BoostUSA"]
    boost[1]["LowerBound"] = 12000                       # 0–10,000 then 12,000–25,000: a gap
    boost[2]["UpperBound"] = 99999                       # the last band closed
    for t in [t for t in tiers if t["RateCardEntryId"] == "@ref:RCE_Commit_FlashANY"]:
        tiers.remove(t)                                  # an entry with no tiers
    path.write_text(json.dumps(data))
    code, out = run("check", config_dir=target)
    assert code != 0, out
    assert "bands must chain: the band before it ends at 10000, this one starts at 12000" in out
    assert "the last band has an UpperBound" in out
    assert "no RateAdjustmentByTier rows prices nothing" in out


