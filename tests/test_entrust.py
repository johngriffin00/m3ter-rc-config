def copy_config(tmp_path: Path) -> Path:
    target = tmp_path / "entrust"
    shutil.copytree(ENTRUST_CONFIG, target, ignore=shutil.ignore_patterns("archive"))
    return target


def load(path: Path) -> dict:
    return json.loads(path.read_text())


def block_of(data: dict, sobject: str) -> dict:
    return next(b for b in data["objects"] if b["sobject"] == sobject)


def test_the_files_on_disk_are_what_the_generator_writes():
    """The config is generated; a hand edit that is not in the generator is lost on the next run,
    and a file the generator no longer writes (the 8 Oct single Base card) must be gone."""
