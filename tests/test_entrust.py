def test_a_new_feature_region_is_an_ordinary_change(org, run, tmp_path):
    """The shape grows by one row in the generator's RESOURCES table — nine records: a resource, its link,
    grant and policy row, an entry on each card and three tiers. No new product, no new price-book entry."""
    run("apply", config_dir=ENTRUST_CONFIG)
    target = copy_config(tmp_path)

    def add(name: str, sobject: str, template: dict, **changes) -> None:
        path = target / name
        data = load(path)
        block_of(data, sobject)["records"].append({**template, **changes})
        path.write_text(json.dumps(data))

    res = block_of(load(target / "04-usage-resources.json"), "UsageResource")["records"][0]
    add("04-usage-resources.json", "UsageResource", res, **{"@id": "RES_BoostREGB"},
        Name="Document Check - Boost - REG-B", Code="RES-DOC-CHECK-BOOST-REG-B")
    junctions = load(target / "07-product-junctions.json")
    add("07-product-junctions.json", "ProductUsageResource", block_of(junctions, "ProductUsageResource")["records"][0],
        **{"@id": "PUR_BoostREGB"}, UsageResourceId="@ref:RES_BoostREGB")
    grants = load(target / "08-grants.json")
    add("08-grants.json", "ProductUsageGrant", block_of(grants, "ProductUsageGrant")["records"][0],
        **{"@id": "PUG_BoostREGB"}, Label="Document Check - Boost - REG-B - Grant",
        ProductUsageResourceId="@ref:PUR_BoostREGB")
    add("08-grants.json", "ProductUsageResourcePolicy", block_of(grants, "ProductUsageResourcePolicy")["records"][0],
        **{"@id": "PURP_BoostREGB"}, ProductUsageResourceId="@ref:PUR_BoostREGB")
    listcard = load(target / "09b-list-rate-card.json")
    add("09b-list-rate-card.json", "RateCardEntry", block_of(listcard, "RateCardEntry")["records"][0],
        **{"@id": "RCE_List_BoostREGB"}, UsageResourceId="@ref:RES_BoostREGB", Rate=6.0)
    commit = load(target / "09c-commit-rate-card.json")
    add("09c-commit-rate-card.json", "RateCardEntry", block_of(commit, "RateCardEntry")["records"][0],
        **{"@id": "RCE_Commit_BoostREGB"}, UsageResourceId="@ref:RES_BoostREGB")
    for low, high, value in ((0, 10000, 0.7), (10000, 25000, 0.6), (25000, None, 0.5)):
        tier = {"@id": f"RAT_BoostREGB_{low}", "RateCardEntryId": "@ref:RCE_Commit_BoostREGB",
                "LowerBound": low, "AdjustmentType": "Override", "AdjustmentValue": value}
        if high is not None:
            tier["UpperBound"] = high
        add("09c-commit-rate-card.json", "RateAdjustmentByTier", tier)

    code, out = run("apply", config_dir=target)
    assert code == 0, out
    assert total(out, "Created") == 9 and total(out, "Unchanged") == OWNED
    assert total(out, "Linked") == 1 and total(out, "Activated") == 5
    assert total(out, "Errors") == 0 and total(out, "Warnings") == 0
    product = org.one("Product2", ProductCode=PRODUCT_CODE)
    assert org.count("ProductUsageResource", ProductId=product["Id"]) == RESOURCES + 1
    assert org.count("RateCardEntry", ProductId=product["Id"]) == 2 * (RESOURCES + 1)
    assert org.count("RateAdjustmentByTier") == (RESOURCES + 1) * TIERS
    assert org.count("PricebookEntry", Product2Id=product["Id"]) == 1


